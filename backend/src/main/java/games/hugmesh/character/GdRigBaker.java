package games.hugmesh.character;

import games.hugmesh.character.Expressions.Pose;
import games.hugmesh.character.HumanoidRig.Joint;
import games.hugmesh.character.HumanoidRig.Part;
import games.hugmesh.character.HumanoidRig.Vec3;

import java.util.Locale;
import java.util.Map;

/**
 * Bakes a {@link CharacterSpec} into the GDScript body of
 * {@code scripts/avatar_config.gd}.
 *
 * <p>The rig is computed <b>here, in Java</b>, and emitted as data;
 * {@code avatar_factory.gd} becomes a dumb instantiator that walks the baked
 * tree. This is what makes 2D/3D/glTF parity structural rather than a review
 * obligation — GDScript no longer holds a single dimension of its own, so it
 * cannot drift from the SVG or the export the way the old hand-written factory
 * drifted from the canvas preview.
 *
 * <p>Two safety properties are load-bearing and pinned by tests:
 * <ul>
 *   <li><b>No raw {@code #rrggbb} ever reaches GDScript.</b> Colours are parsed
 *       to {@code Color(r, g, b)} floats here. Only whitelisted tokens and
 *       numbers cross the boundary, so nothing free-form is ever spliced into
 *       generated code.</li>
 *   <li><b>Every float is formatted with {@link Locale#ROOT}.</b> A
 *       comma-decimal default locale would emit {@code Vector3(0,3, 1,2, 0)} and
 *       produce a bundle that fails to parse at runtime — the same class of bug
 *       that bites generated SVG coordinates.</li>
 * </ul>
 */
public final class GdRigBaker {

    private GdRigBaker() {}

    /** The complete contents of {@code scripts/avatar_config.gd}. */
    public static String bake(CharacterSpec spec) {
        StringBuilder sb = new StringBuilder(4096);
        sb.append("# Generated by hugmesh-rpg-builder. Do not hand-edit.\n");
        sb.append("# Whitelisted tokens, numbers and Color floats only — no raw hex, no\n");
        sb.append("# free-form text. Consumed by avatar_factory.gd (geometry) and\n");
        sb.append("# avatar_poser.gd (animation + expressions).\n\n");

        appendAvatarDict(sb, spec);
        sb.append("\nconst STYLE := \"").append(spec.renderStyle()).append("\"\n\n");
        appendRig(sb, spec);
        sb.append('\n');
        appendExpressions(sb, spec);
        return sb.toString();
    }

    // ── AVATAR: the raw parameter dict, kept for back-compat and debugging ───

    private static void appendAvatarDict(StringBuilder sb, CharacterSpec spec) {
        sb.append("const AVATAR := {\n");
        kv(sb, "render_style", spec.renderStyle());
        kv(sb, "body_shape", spec.bodyShape());
        kv(sb, "head_shape", spec.headShape());
        kv(sb, "hair_style", spec.hairStyle());
        kv(sb, "outfit_type", spec.outfitType());
        kv(sb, "hat_type", spec.hatType());
        kv(sb, "held_main", spec.heldMain());
        kv(sb, "held_off", spec.heldOff());
        kv(sb, "back_item", spec.backItem());
        kv(sb, "face_item", spec.faceItem());
        for (CharacterSpec.Bound b : CharacterSpec.PROPORTIONS) {
            sb.append("    \"").append(snake(b.key())).append("_scale\": ")
                    .append(f3(spec.p(b.key()))).append(",\n");
        }
        for (CharacterSpec.ColorSlot c : CharacterSpec.COLORS) {
            sb.append("    \"").append(c.key()).append("_color\": ")
                    .append(color(spec.color(c.key()))).append(",\n");
        }
        sb.append("}\n");
    }

    // ── RIG: the joint tree the factory instantiates ─────────────────────────

    private static void appendRig(StringBuilder sb, CharacterSpec spec) {
        sb.append("const RIG := ");
        appendJoint(sb, HumanoidRig.of(spec), 0);
        sb.append('\n');
    }

    private static void appendJoint(StringBuilder sb, Joint joint, int depth) {
        String pad = "\t".repeat(depth + 1);
        sb.append("{\n");
        sb.append(pad).append("\"name\": \"").append(joint.name).append("\",\n");
        sb.append(pad).append("\"pos\": ").append(vec(joint.pos)).append(",\n");

        sb.append(pad).append("\"parts\": [");
        if (!joint.parts.isEmpty()) {
            sb.append('\n');
            for (Part p : joint.parts) {
                sb.append(pad).append('\t');
                appendPart(sb, p);
                sb.append(",\n");
            }
            sb.append(pad);
        }
        sb.append("],\n");

        sb.append(pad).append("\"children\": [");
        if (!joint.children.isEmpty()) {
            sb.append('\n');
            for (Joint c : joint.children) {
                sb.append(pad).append('\t');
                appendJoint(sb, c, depth + 2);
                sb.append(",\n");
            }
            sb.append(pad);
        }
        sb.append("],\n");
        sb.append("\t".repeat(depth)).append('}');
    }

    private static void appendPart(StringBuilder sb, Part p) {
        sb.append("{\"name\": \"").append(p.name())
                .append("\", \"shape\": \"").append(p.shape().name().toLowerCase(Locale.ROOT))
                .append("\", \"pos\": ").append(vec(p.pos()))
                .append(", \"size\": ").append(vec(p.size()))
                .append(", \"rot\": ").append(vec(p.rot()))
                .append(", \"taper\": ").append(f(p.taper()))
                .append(", \"color\": ").append(color(p.color()))
                .append(", \"tex\": \"").append(p.tex())
                .append("\", \"slot\": \"").append(p.slot())
                .append("\"}");
    }

    // ── EXPRESSIONS: the same resolved table the SVG uses ───────────────────

    private static void appendExpressions(StringBuilder sb, CharacterSpec spec) {
        sb.append("const EXPRESSIONS := {\n");
        Map<String, Map<String, Pose>> all = Expressions.resolveAll(spec);
        for (Map.Entry<String, Map<String, Pose>> e : all.entrySet()) {
            sb.append("\t\"").append(e.getKey()).append("\": {\n");
            for (Map.Entry<String, Pose> j : e.getValue().entrySet()) {
                Pose pose = j.getValue();
                sb.append("\t\t\"").append(j.getKey()).append("\": {")
                        .append("\"offset\": ").append(vec(pose.offset()))
                        .append(", \"scale\": ").append(vec(pose.scale()))
                        .append(", \"rot\": ").append(vec(pose.rot()))
                        .append("},\n");
            }
            sb.append("\t},\n");
        }
        sb.append("}\n");
    }

    // ── Emitters ────────────────────────────────────────────────────────────

    private static void kv(StringBuilder sb, String key, String value) {
        sb.append("    \"").append(key).append("\": \"").append(value).append("\",\n");
    }

    private static String vec(Vec3 v) {
        return "Vector3(" + f(v.x()) + ", " + f(v.y()) + ", " + f(v.z()) + ")";
    }

    /**
     * {@code #rrggbb} → {@code Color(r, g, b)}. The hex never crosses into
     * GDScript; {@link CharacterSpec} has already guaranteed the format, and
     * this asserts rather than re-deriving that guarantee.
     */
    private static String color(String hex) {
        if (hex == null || !hex.matches("^#[0-9a-fA-F]{6}$")) {
            throw new IllegalStateException("unvalidated colour reached the baker: " + hex);
        }
        double r = Integer.parseInt(hex.substring(1, 3), 16) / 255.0;
        double g = Integer.parseInt(hex.substring(3, 5), 16) / 255.0;
        double b = Integer.parseInt(hex.substring(5, 7), 16) / 255.0;
        return "Color(" + f3(r) + ", " + f3(g) + ", " + f3(b) + ")";
    }

    /**
     * Rig geometry: sub-millimetre precision, so a proportion slider produces a
     * visible change rather than quantising away.
     *
     * <p>Locale.ROOT is load-bearing on both formatters — a comma-decimal
     * default locale would emit {@code Vector3(0,3, 1,2, 0)} and produce a
     * bundle that fails to parse at runtime.
     */
    private static String f(double v) {
        return String.format(Locale.ROOT, "%.4f", v);
    }

    /** Parameters and colours: three places, matching the pre-028 bake exactly. */
    private static String f3(double v) {
        return String.format(Locale.ROOT, "%.3f", v);
    }

    /** {@code armLength} → {@code arm_length}, matching the column names. */
    private static String snake(String camel) {
        StringBuilder out = new StringBuilder(camel.length() + 4);
        for (char c : camel.toCharArray()) {
            if (Character.isUpperCase(c)) out.append('_').append(Character.toLowerCase(c));
            else out.append(c);
        }
        return out.toString();
    }
}
