"""
Render the merged OpenAPI spec (openapi.json + metadata) as LaTeX
fragments the architecture PDF and user-guide PDFs can \\input.

Outputs into docs/publishing/openapi/build/:
  openapi-summary.tex          — one tabularx of all operations
                                 (tag, method, path, summary).
  per-tag/<slug>.tex           — one fragment per tag with full
                                 long-form prose + samples + flags.

LaTeX is written using the snapdragon-theme macros (\snapfile,
\snapcommand, snapnote/snapcaution boxes, lstlisting JSON style)
so the fragments drop into existing chapters with no extra setup.

Idempotent — re-running with the same merged spec produces byte-
identical fragments.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from textwrap import indent


HTTP_METHODS = ("get", "post", "put", "delete", "patch", "options", "head")


# ── Tex helpers ─────────────────────────────────────────────────────────────
TEX_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
    "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}
def tex(s: str) -> str:
    """Escape a plain string for use inside running LaTeX text."""
    if s is None:
        return ""
    out = []
    for ch in str(s):
        out.append(TEX_ESCAPES.get(ch, ch))
    return "".join(out)


def tex_code(s: str) -> str:
    """Escape for inside \\texttt{...} — same escapes, kept as one helper."""
    return tex(s)


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", str(s).lower()).strip("-")


def code_listing(payload, language="json") -> str:
    """
    Render a python value as a fenced code block. Falls back to raw
    text for strings (used for SSE example chunks).
    """
    if payload is None:
        return ""
    if isinstance(payload, str):
        rendered = payload
    else:
        rendered = json.dumps(payload, indent=2, sort_keys=False)
    return (
        "\\begin{lstlisting}[language=" + language + "]\n"
        + rendered
        + "\n\\end{lstlisting}\n"
    )


# ── Top-level renderers ─────────────────────────────────────────────────────
def render_summary_table(ops: list[dict]) -> str:
    lines = [
        "% Auto-generated by spec-to-latex.py — do not edit by hand.",
        "% Source: docs/publishing/openapi/build/openapi.json",
        "",
        "\\begingroup\\small",
        "\\begin{tabularx}{\\linewidth}{@{}l l >{\\raggedright\\arraybackslash}p{0.32\\linewidth} >{\\raggedright\\arraybackslash}X@{}}",
        "\\toprule",
        "\\textbf{Tag} & \\textbf{Method} & \\textbf{Path} & \\textbf{Summary} \\\\",
        "\\midrule",
    ]
    for op in ops:
        lines.append(
            f"{tex(op['tag'])} & "
            f"\\texttt{{{op['method'].upper()}}} & "
            f"\\snapfile{{{op['path']}}} & "
            f"{tex(op.get('summary',''))} \\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabularx}",
        "\\endgroup",
        "",
    ]
    return "\n".join(lines)


def render_tag_fragment(tag_name: str, tag_meta: dict,
                        ops: list[dict]) -> str:
    out = [
        f"% Auto-generated — tag: {tag_name}",
        "% Source: docs/publishing/openapi/build/openapi.json",
        "",
        f"\\subsection*{{{tex(tag_name)}}}",
    ]
    snap = tag_meta.get("x-snapdragon", {}) if isinstance(tag_meta, dict) else {}
    blurb = snap.get("blurb") or tag_meta.get("description")
    if blurb:
        out.append(tex(blurb))
        out.append("")
    chapter = snap.get("chapter")
    marble  = snap.get("marble")
    if chapter or marble:
        # The bits contain literal LaTeX commands (\S, \snapfile{...}) that
        # MUST NOT be passed through tex() — that would re-escape the
        # backslashes and ruin the cross-ref. The chapter / marble values
        # are author-controlled and we constrain them to safe characters
        # (digits, dots, lowercase, slashes, hyphens).
        bits = []
        if chapter:
            bits.append(f"Architecture PDF \\S{chapter}")
        if marble:
            bits.append(f"marble at \\snapfile{{{marble}}}")
        out.append("\\textit{" + " --- ".join(bits) + ".}")
        out.append("")

    for op in ops:
        out.append(
            f"\\paragraph{{\\texttt{{{op['method'].upper()} {tex_code(op['path'])}}}}}"
        )
        if op.get("summary"):
            out.append(tex(op["summary"]))
            out.append("")
        snap_op = op.get("snap", {})
        long_desc = snap_op.get("longDescription") or op.get("description")
        if long_desc:
            out.append(tex(long_desc))
            out.append("")
        if snap_op.get("sse"):
            out.append("\\textbf{SSE.} This endpoint streams via "
                       "\\texttt{text/event-stream}; the API explorer "
                       "renders incoming events into a terminal panel.")
            out.append("")
            if snap_op.get("sampleEvent"):
                out.append(code_listing(snap_op["sampleEvent"], language=""))
        if snap_op.get("binaryUpload"):
            bu = snap_op["binaryUpload"]
            out.append(
                "\\textbf{Binary upload.} Field "
                f"\\texttt{{{tex_code(bu.get('field','file'))}}}, "
                f"accepts \\texttt{{{tex_code(bu.get('accept','*/*'))}}}: "
                f"{tex(bu.get('description',''))}"
            )
            out.append("")
        if snap_op.get("sampleRequest"):
            out.append("\\textit{Sample request:}")
            out.append(code_listing(snap_op["sampleRequest"]))
        if snap_op.get("sampleResponse"):
            out.append("\\textit{Sample response:}")
            out.append(code_listing(snap_op["sampleResponse"]))
        out.append("")

    return "\n".join(out)


# ── Main ────────────────────────────────────────────────────────────────────
def collect_operations(spec: dict) -> list[dict]:
    rows = []
    for path, ops in spec.get("paths", {}).items():
        for method, op in (ops or {}).items():
            if method.lower() not in HTTP_METHODS:
                continue
            if not isinstance(op, dict):
                continue
            tag = (op.get("tags") or ["Untagged"])[0]
            rows.append({
                "tag":     tag,
                "method":  method,
                "path":    path,
                "summary": op.get("summary", ""),
                "description": op.get("description", ""),
                "snap":    op.get("x-snapdragon", {}),
                "responses": op.get("responses", {}),
            })
    rows.sort(key=lambda r: (r["tag"], r["path"], r["method"]))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", required=True, type=Path)
    ap.add_argument("--out-dir", required=True, type=Path)
    args = ap.parse_args()

    spec = json.loads(args.spec.read_text())
    args.out_dir.mkdir(parents=True, exist_ok=True)
    per_tag_dir = args.out_dir / "per-tag"
    per_tag_dir.mkdir(parents=True, exist_ok=True)

    ops = collect_operations(spec)

    # Tag map (preserve declaration order from spec.tags, then any
    # tag found only in operations).
    tag_meta = {t["name"]: t for t in spec.get("tags", []) if isinstance(t, dict)}
    by_tag: dict[str, list[dict]] = {}
    for op in ops:
        by_tag.setdefault(op["tag"], []).append(op)

    # Summary table
    (args.out_dir / "openapi-summary.tex").write_text(
        render_summary_table(ops)
    )

    # Per-tag fragments
    written = []
    for tag_name in [*tag_meta.keys(), *by_tag.keys()]:
        if tag_name in written:
            continue
        rows = by_tag.get(tag_name, [])
        if not rows:
            continue
        path = per_tag_dir / f"{slug(tag_name)}.tex"
        path.write_text(
            render_tag_fragment(tag_name,
                                tag_meta.get(tag_name, {}),
                                rows)
        )
        written.append(tag_name)

    print(f"  ✓ {len(ops)} operations across {len(written)} tag(s)")
    print(f"  ✓ summary: {args.out_dir / 'openapi-summary.tex'}")
    for t in written:
        print(f"      {per_tag_dir / (slug(t) + '.tex')}")


if __name__ == "__main__":
    main()
