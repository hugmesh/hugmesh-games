package games.hugmesh.vnbuilder.controller;

import games.hugmesh.vnbuilder.build.VnGodotProjectRenderer;
import games.hugmesh.vnbuilder.entity.VnProject;
import games.hugmesh.vnbuilder.security.Roles;
import games.hugmesh.vnbuilder.service.VnProjectService;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.security.core.Authentication;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;
import reactor.core.publisher.Mono;
import reactor.core.scheduler.Schedulers;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.UUID;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

/**
 * Mirror of the rpg-builder GodotSourceController — lets a publisher
 * download the rendered Godot 4 source for a VN project so they can
 * edit in the Godot editor and re-upload through the BFF upload
 * endpoint.
 */
@RestController
@RequestMapping("/api/vn")
@PreAuthorize("hasAnyRole('ADMIN','PUBLISHER')")
public class GodotSourceController {

    private final VnProjectService projects;
    private final VnGodotProjectRenderer renderer;
    private final Path tempRoot;

    public GodotSourceController(VnProjectService projects,
                                 VnGodotProjectRenderer renderer,
                                 @Value("${app.build.workdir}") String workdir) {
        this.projects = projects;
        this.renderer = renderer;
        this.tempRoot = Path.of(workdir).resolve("downloads");
    }

    @GetMapping("/projects/{pid}/godot-zip")
    public Mono<ResponseEntity<byte[]>> download(@PathVariable UUID pid, Authentication auth) {
        String owner = Roles.principalOf(auth);
        return projects.get(pid, owner).flatMap(project ->
                Mono.fromCallable(() -> Files.createDirectories(tempRoot.resolve(pid.toString())))
                        .subscribeOn(Schedulers.boundedElastic())
                        .then(renderer.render(project, tempRoot.resolve(pid.toString())))
                        .flatMap(rendered -> Mono.fromCallable(() -> packageZip(rendered.godotSrcRoot(), project))
                                .subscribeOn(Schedulers.boundedElastic())));
    }

    private static ResponseEntity<byte[]> packageZip(Path srcRoot, VnProject project) throws IOException {
        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        try (ZipOutputStream zos = new ZipOutputStream(baos)) {
            try (var walk = Files.walk(srcRoot)) {
                walk.filter(Files::isRegularFile).forEach(p -> {
                    String rel = srcRoot.relativize(p).toString().replace('\\', '/');
                    try {
                        zos.putNextEntry(new ZipEntry(rel));
                        zos.write(Files.readAllBytes(p));
                        zos.closeEntry();
                    } catch (IOException io) { throw new RuntimeException(io); }
                });
            }
            zos.putNextEntry(new ZipEntry("bin/README.md"));
            zos.write(BIN_PLACEHOLDER.getBytes());
            zos.closeEntry();
            zos.putNextEntry(new ZipEntry("README.md"));
            zos.write(buildReadme(project).getBytes());
            zos.closeEntry();
        }
        return ResponseEntity.ok()
                .contentType(MediaType.APPLICATION_OCTET_STREAM)
                .header(HttpHeaders.CONTENT_DISPOSITION,
                        "attachment; filename=\"" + project.getSlug() + "-godot.zip\"")
                .body(baos.toByteArray());
    }

    private static final String BIN_PLACEHOLDER = """
            # hugmesh_bridge native binaries

            Build the matching binary from the host repo (`make build-rust`)
            and drop it here:

            * Linux  : libhugmesh_bridge.so
            * Windows: hugmesh_bridge.dll
            * macOS  : libhugmesh_bridge.dylib
            * Web    : hugmesh_bridge.wasm
            """;

    private static String buildReadme(VnProject project) {
        return """
                # %s — Godot source

                Generated by hugmesh-vn-builder for editing in Godot 4.

                ## Open in Godot

                1. `cd` into this directory.
                2. Run `godot --editor project.godot`.
                3. Wire any extension binaries you need into `bin/`.
                4. Hit F5 / play.

                ## Re-upload

                Run the Godot exporter via the bundled `export_presets.cfg`,
                then upload the zip through the publisher console at
                `/publisher`.

                ## Multiplayer

                The scene tree includes a `HugMeshMultiplayerLobby` node so
                avatars parented under `Wizards` automatically participate in
                the per-session lobby + view channel.
                """.formatted(project.getDisplayName());
    }
}
